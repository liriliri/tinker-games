export const ckmv2: boolean[][] = []
export const ckmv3: boolean[][] = []
export const skipAxis2 = new Int32Array(28)
export const skipAxis3 = new Int32Array(20)

let movesInited = false

export function initMoves(): void {
  if (movesInited) return
  movesInited = true
  const ckmv: boolean[][] = []
  for (let i = 0; i < 36; i++) {
    ckmv[i] = new Array(36)
    for (let j = 0; j < 36; j++) {
      ckmv[i][j] =
        Math.floor(i / 3) === Math.floor(j / 3) ||
        (Math.floor(i / 3) % 3 === Math.floor(j / 3) % 3 && i > j)
    }
  }
  ckmv[36] = new Array(36).fill(false)
  for (let i = 0; i < 29; i++) {
    ckmv2[i] = new Array(28)
    for (let j = 0; j < 28; j++) {
      ckmv2[i][j] = ckmv[move2std[i]][move2std[j]]
    }
  }
  for (let i = 0; i < 21; i++) {
    ckmv3[i] = new Array(20)
    for (let j = 0; j < 20; j++) {
      ckmv3[i][j] = ckmv[move3std[i]][move3std[j]]
    }
  }
  for (let i = 0; i < 28; i++) {
    skipAxis2[i] = 28
    for (let j = i; j < 28; j++) {
      if (!ckmv2[i][j]) {
        skipAxis2[i] = j - 1
        break
      }
    }
  }
  for (let i = 0; i < 20; i++) {
    skipAxis3[i] = 20
    for (let j = i; j < 20; j++) {
      if (!ckmv3[i][j]) {
        skipAxis3[i] = j - 1
        break
      }
    }
  }
}
